fn canonical(german: &str) -> String {
    print(&parse_input(german, De, |_| false).unwrap_or_else(|e| panic!("`{german}`: {e}")))
}

fn german(canonical: &str) -> String {
    print_input(&parse(canonical).unwrap_or_else(|e| panic!("`{canonical}`: {e}")), De, |_| false).unwrap()
}

#[test]
fn every_function_is_spelled_as_german_excel_shows_it() {
    let mut wrong = Vec::new();
    for (entered, shown) in FUNCTIONS.iter().chain(SYNTAX) {
        let ours = german(entered);
        if ours != *shown {
            wrong.push(format!("{entered}: shown {ours} (Excel: {shown})"));
        }
    }
    assert!(wrong.is_empty(), "{} differ from Excel:\n{}", wrong.len(), wrong.join("\n"));
}

#[test]
fn what_german_excel_shows_reads_back_as_the_formula() {
    for (entered, shown) in FUNCTIONS.iter().chain(SYNTAX) {
        assert_eq!(canonical(shown), print(&parse(entered).unwrap()), "{shown}");
    }
}

#[test]
fn the_observation_covers_every_function_the_table_lists() {
    // Every table entry was observed; a name added to the table without an observation fails here.
    for (en, local) in De.translations() {
        let call = FUNCTIONS.iter().find(|(entered, _)| entered.strip_prefix(en).is_some_and(|rest| rest.starts_with('(')));
        let (_, shown) = call.unwrap_or_else(|| panic!("{en} was not observed"));
        assert!(shown.starts_with(&format!("{local}(")), "{en}: table {local}, Excel {shown}");
    }
    assert_eq!(FUNCTIONS.len(), 519);
}

#[test]
fn typed_german_also_accepts_the_long_this_row_specifier_and_lower_case() {
    // Observed: `[#Diese Zeile]` is accepted when typed, and shown as `@`.
    assert_eq!(canonical("Tbl[[#Diese Zeile];[H1]]"), "Tbl[@H1]");
    assert_eq!(canonical("ZEILEN(Tbl[#Diese Zeile])"), "ROWS(Tbl[@])");
    assert_eq!(canonical("summe(tbl[[#kopfzeilen];[h1]])"), "SUM(tbl[[#Headers],[h1]])");
    assert_eq!(canonical("wenn(wahr;1;#nv)"), "IF(TRUE,1,#N/A)");
    // GridCraft also reads the canonical #SPILL! and #CALC!, and German Excel's #ÜBERLAUF!.
    assert_eq!(canonical("ISTFEHLER(#ÜBERLAUF!)"), "ISERROR(#SPILL!)");
    assert_eq!(german("ISERROR(#SPILL!)+ISERROR(#CALC!)"), "ISTFEHLER(#ÜBERLAUF!)+ISTFEHLER(#CALC!)");
}

#[test]
fn german_input_never_panics() {
    // German-looking fragments joined at random: the parser answers, it never panics.
    let pieces: Vec<&str> = FUNCTIONS
        .iter()
        .map(|(_, shown)| *shown)
        .chain([
            "(",
            ")",
            ";",
            ",",
            ".",
            "{",
            "}",
            "[",
            "]",
            "#",
            "#NV",
            "#WERT",
            "WAHR",
            "\"",
            "'",
            "@",
            ":",
            "!",
            "1,5",
            "1.",
            ".:",
            "€",
            "Ü",
            "%",
            " ",
            "Tbl[[#Kopfzeilen];",
            "[#Diese Zeile]",
        ])
        .collect();
    let mut seed: u64 = 0x5eed_dede;
    let mut next = |n: usize| {
        seed ^= seed << 13;
        seed ^= seed >> 7;
        seed ^= seed << 17;
        (seed % n.max(1) as u64) as usize
    };
    for _ in 0..4000 {
        let len = next(8) + 1;
        let src: String = (0..len).map(|_| pieces[next(pieces.len())]).collect();
        let _ = parse_input(&src, De, |_| false);
        if let Ok(expr) = parse(&src) {
            let _ = print_input(&expr, De, |_| false);
        }
        let _ = FormulaLocale::De.canonical_name(&src);
    }
}
